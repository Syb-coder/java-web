package com.example.java7.model; // 声明包路径为 com.example.java7.model，存放领域模型类

/**
 * 图书分类枚举
 * <p>
 * 职责：定义系统支持的图书分类，使用枚举避免魔法字符串，保证类型安全。
 * 分类设计参考常见家庭藏书结构，覆盖主流阅读类型。
 * </p>
 * <p>
 * 设计要点：
 * 1. 使用枚举而非字符串常量，编译期即可发现非法取值；
 * 2. 每个枚举项关联中文显示名称，便于前端直接展示；
 * 3. 枚举值不可变，天然线程安全，适合多线程环境访问。
 * </p>
 */
public enum BookCategory { // 定义公共枚举 BookCategory，表示图书分类

    /** 文学小说：中外文学、小说、散文、诗歌等 */
    LITERATURE("文学小说"), // 文学小说分类，构造时传入中文显示名称

    /** 科技计算机：计算机、工程、自然科学类 */
    TECHNOLOGY("科技计算机"), // 科技计算机分类

    /** 人文历史：历史、地理、传记、哲学等 */
    HISTORY("人文历史"), // 人文历史分类

    /** 经济管理：经济、金融、管理、商业类 */
    ECONOMICS("经济管理"), // 经济管理分类

    /** 艺术设计：美术、音乐、摄影、设计类 */
    ART("艺术设计"), // 艺术设计分类

    /** 生活休闲：健康、烹饪、旅游、运动类 */
    LIFE("生活休闲"), // 生活休闲分类

    /** 少儿读物：儿童文学、绘本、科普等 */
    CHILDREN("少儿读物"), // 少儿读物分类

    /** 其他：未归入上述分类的图书 */
    OTHER("其他"); // 其他分类，末尾使用分号结束枚举常量列表

    /** 分类显示名称，用于前端展示 */
    private final String displayName; // 中文显示名称字段，final 修饰保证不可变，确保线程安全

    /**
     * 枚举构造方法
     * <p>
     * 枚举的构造方法默认为 private，由 JVM 在枚举类初始化时调用，
     * 不允许外部直接 new 创建实例。
     * </p>
     *
     * @param displayName 中文显示名称
     */
    BookCategory(String displayName) { // 枚举构造方法，private 修饰（默认隐含）
        this.displayName = displayName; // 将传入的显示名称赋值给成员变量
    }

    /**
     * 获取分类中文显示名称
     * <p>
     * 提供给前端展示使用，避免前端硬编码中文映射，
     * 实现显示逻辑与数据定义的解耦。
     * </p>
     *
     * @return 显示名称
     */
    public String getDisplayName() { // 公共访问方法，返回枚举的中文显示名称
        return displayName; // 返回成员变量 displayName 的值
    }
}
