package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 支付订单状态枚举
 * <p>
 * 描述支付收银台订单的生命周期：
 * - PENDING：待支付（订单已创建，等待用户付款）；
 * - PAID：已支付（资金已到账）；
 * - FAILED：支付失败（渠道异常或余额不足）；
 * - REFUNDED：已退款（发起退款并成功）。
 * </p>
 */
public enum PaymentStatus {  // 支付订单状态枚举，覆盖从下单到退款的完整流程
    /** 待支付 */
    PENDING,   // 待支付：订单已创建，等待用户付款，超时自动关闭
    /** 已支付 */
    PAID,      // 已支付：渠道回调确认资金到账，可触发下游业务
    /** 支付失败 */
    FAILED,    // 支付失败：渠道异常或余额不足，可重试或更换渠道
    /** 已退款 */
    REFUNDED   // 已退款：发起退款并成功，资金原路退回用户账户
}
