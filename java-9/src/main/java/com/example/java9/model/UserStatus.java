package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * C端用户状态枚举
 * <p>
 * 用于标识用户账户当前状态：
 * - NORMAL：正常状态，可进行所有业务操作；
 * - FROZEN：冻结状态，由风控或运营触发，禁止交易与提现。
 * </p>
 */
public enum UserStatus {  // C端用户状态枚举，控制账户可用性，影响交易、提现等核心业务流程
    /** 正常状态 */
    NORMAL,  // 正常状态：账户可用，可进行所有业务操作（投资、支付、提现等）
    /** 冻结状态（风控触发） */
    FROZEN   // 冻结状态：由风控或运营触发，禁止交易与提现，但允许登录查看
}
