package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 管理员角色枚举
 * <p>
 * 区分后台管理员职责，用于权限拦截与菜单分发：
 * - OPERATION：运营管理员，负责用户/商户/产品/活动管理；
 * - RISK：风控专员，负责风险识别、合规审计、违规处理。
 * </p>
 */
public enum AdminRole {  // 管理员角色枚举，配合 Spring Security 或拦截器做权限隔离
    /** 运营管理员 */
    OPERATION,  // 运营管理员：负责用户/商户/产品/活动的日常管理与审核
    /** 风控专员 */
    RISK        // 风控专员：负责风险识别、合规审计、违规处置，权限与运营隔离以避免越权
}
