package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 优惠券状态枚举
 * <p>
 * 优惠券生命周期：
 * - UNUSED：未使用（已领取，有效期内）；
 * - USED：已使用（已抵扣投资或支付）；
 * - EXPIRED：已过期（超过有效期自动作废）。
 * </p>
 */
public enum CouponStatus {  // 优惠券状态枚举，控制可用性并支撑过期/核销定时任务
    /** 未使用 */
    UNUSED,   // 未使用：已领取且在有效期内，可在收银台核销
    /** 已使用 */
    USED,     // 已使用：已抵扣投资或支付，关联订单号用于对账
    /** 已过期 */
    EXPIRED   // 已过期：超过有效期自动作废，定时任务批量扫描置为此状态
}
