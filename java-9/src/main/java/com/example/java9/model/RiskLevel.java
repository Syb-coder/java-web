package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 风控记录风险等级枚举
 * <p>
 * 风控规则引擎输出的风险分级，决定处置优先级：
 * - LOW：低风险（系统记录，不阻断交易）；
 * - MEDIUM：中风险（需人工复核，可临时限额）；
 * - HIGH：高风险（立即冻结账户或订单，强制人工介入）。
 * </p>
 */
public enum RiskLevel {  // 风控等级枚举，决定处置优先级与自动化干预策略
    /** 低风险 */
    LOW,     // 低风险：系统记录留痕，不阻断交易，用于风控建模数据积累
    /** 中风险 */
    MEDIUM,  // 中风险：需人工复核，可临时限额，进入风控专员待办队列
    /** 高风险 */
    HIGH     // 高风险：立即冻结账户或订单，强制人工介入，避免资金损失扩大
}
