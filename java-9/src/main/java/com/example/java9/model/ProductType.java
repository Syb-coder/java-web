package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 理财产品类型枚举
 * <p>
 * 对应底层理财业务的不同产品形态：
 * - DEPOSIT：定期存款类（低风险、固定收益）；
 * - FUND：基金类（中风险、浮动收益）；
 * - INSURANCE：保险理财类（中长期、保障+收益）。
 * </p>
 */
public enum ProductType {  // 理财产品类型枚举，决定风控策略、收益计算规则与展示分类
    /** 定期存款类 */
    DEPOSIT,    // 定期存款类：低风险、固定收益，适合保守型用户
    /** 基金类 */
    FUND,       // 基金类：中风险、浮动收益，需展示净值波动提示
    /** 保险理财类 */
    INSURANCE   // 保险理财类：中长期、保障+收益，需披露保险条款
}
