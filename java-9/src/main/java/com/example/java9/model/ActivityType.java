package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 营销活动类型枚举
 * <p>
 * 区分营销活动的业务形态，影响优惠券发放与权益计算逻辑：
 * - COUPON：理财优惠券（满减抵扣）；
 * - INTEREST_RATE：加息活动（限时加息收益）；
 * - SIGN_IN：签到福利（每日签到领积分/小额返现）。
 * </p>
 */
public enum ActivityType {  // 营销活动类型枚举，决定权益发放逻辑与效果统计维度
    /** 理财优惠券 */
    COUPON,         // 理财优惠券：满减抵扣，投资时核销，影响订单实际支付金额
    /** 加息活动 */
    INTEREST_RATE,  // 加息活动：限时加息收益，在基础年化上叠加加息券
    /** 签到福利 */
    SIGN_IN         // 签到福利：每日签到领积分/小额返现，提升日活与留存
}
