package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 理财产品上架状态枚举
 * <p>
 * 控制产品在 C 端的可见性与可投性：
 * - ON_SALE：在售（用户可见可申购）；
 * - SOLD_OUT：售罄（额度已满，不可再投）；
 * - OFF_SHELF：下架（运营主动下架，不可见）。
 * </p>
 */
public enum ProductStatus {  // 理财产品上架状态枚举，控制 C 端可见性与可投性
    /** 在售 */
    ON_SALE,    // 在售：用户可见可申购，正常销售中
    /** 售罄 */
    SOLD_OUT,   // 售罄：募集额度已满，自动转入不可投，但展示历史信息
    /** 下架 */
    OFF_SHELF   // 下架：运营主动下架，C 端不可见，已投用户仍可查看持仓
}
