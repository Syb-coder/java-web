package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 客服工单状态枚举
 * <p>
 * 工单流转状态：
 * - OPEN：待处理（用户刚提交，等待客服回复）；
 * - REPLIED：已回复（客服已回复，等待用户确认）；
 * - CLOSED：已关闭（问题已解决或用户主动关闭）。
 * </p>
 */
public enum TicketStatus {  // 客服工单状态枚举，驱动工单看板与 SLA 计时
    /** 待处理 */
    OPEN,     // 待处理：用户刚提交，等待客服回复，SLA 计时开始
    /** 已回复 */
    REPLIED,  // 已回复：客服已回复，等待用户确认或追问，反向 SLA 计时
    /** 已关闭 */
    CLOSED    // 已关闭：问题已解决或用户主动关闭，归档不可再回复
}
