package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 投资订单状态枚举
 * <p>
 * 描述用户申购理财产品的订单生命周期：
 * - PENDING：待确认（刚提交，底层资金清算中）；
 * - CONFIRMED：已确认（资金已划扣，开始计息）；
 * - REDEEMED：已赎回（期满或提前赎回，本息已返还）。
 * </p>
 */
public enum InvestmentStatus {  // 投资订单状态枚举，描述申购到赎回的完整生命周期
    /** 待确认 */
    PENDING,    // 待确认：订单刚提交，底层资金清算中，尚未计息
    /** 已确认（计息中） */
    CONFIRMED,  // 已确认：资金已划扣，开始计息，进入持有期
    /** 已赎回 */
    REDEEMED    // 已赎回：期满或提前赎回，本息已返还，订单终结
}
