package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 交易流水类型枚举
 * <p>
 * 底层资金清算的流水分类，覆盖全平台资金流动场景：
 * - RECHARGE：充值（用户/商户充值入账）；
 * - WITHDRAW：提现（用户/商户提现出账）；
 * - INVEST：投资（用户申购理财扣款）；
 * - REDEEM：赎回（理财本息返还入账）；
 * - PAY：支付（用户向商户付款）；
 * - REFUND：退款（商户或平台退款）。
 * </p>
 */
public enum TransactionType {  // 交易流水类型枚举，用于资金对账与会计科目映射
    /** 充值 */
    RECHARGE,  // 充值：用户/商户充值入账，资金流入平台账户
    /** 提现 */
    WITHDRAW,  // 提现：用户/商户提现出账，资金流出平台账户
    /** 投资 */
    INVEST,    // 投资：用户申购理财扣款，资金从用户余额划扣至产品账户
    /** 赎回 */
    REDEEM,    // 赎回：理财本息返还入账，资金从产品账户划回用户余额
    /** 支付 */
    PAY,       // 支付：用户向商户付款，资金从用户账户转移至商户账户
    /** 退款 */
    REFUND     // 退款：商户或平台发起退款，资金原路退回用户账户
}
