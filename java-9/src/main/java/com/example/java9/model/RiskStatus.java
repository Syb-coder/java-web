package com.example.java9.model;  // 当前枚举所在的包路径，归属于 model 实体/枚举层

/**
 * 风控记录状态枚举
 * <p>
 * 风控记录的处理进度：
 * - PENDING：待处理（系统刚识别，等待风控专员介入）；
 * - HANDLED：已处理（风控专员已确认并处置）；
 * - IGNORED：已忽略（经核实为误报，标记忽略）。
 * </p>
 */
public enum RiskStatus {  // 风控记录状态枚举，跟踪风控工单的处置进度
    /** 待处理 */
    PENDING,   // 待处理：系统刚识别风险，等待风控专员介入处置
    /** 已处理 */
    HANDLED,   // 已处理：风控专员已确认并完成处置（冻结/限额/解冻等）
    /** 已忽略（误报） */
    IGNORED    // 已忽略：经核实为误报，标记忽略以避免重复告警
}
